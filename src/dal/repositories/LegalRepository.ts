/**
 * Intelligent template parser for substituting company tags into raw legal text
 */
export function substituteLegalVariables(text: string, settings: LegalSettings): string {
  if (!text) return '';
  const map: Record<string, string> = {
    'company.name': settings.company_name,
    'company.short_name': settings.company_short_name,
    'company.ogrn': settings.ogrn,
    'company.inn': settings.inn,
    'company.kpp': settings.kpp,
    'company.address': settings.legal_address,
    'company.legal_address': settings.legal_address,
    'company.moscow_office': settings.moscow_office,
    'company.bank_details': settings.bank_details,
    'company.dpo_name': settings.dpo_name,
    'company.support_phone': settings.support_phone,
    'company.phone': settings.support_phone,
    'company.legal_email': settings.legal_email,
    'company.privacy_email': settings.privacy_email,
    'company.partners_email': settings.partners_email,
    'company.banks_email': settings.banks_email,
    'company.security_email': settings.security_email,
    'company.security_phone': settings.security_phone,
    'company.domain_url': settings.domain_url,
    'company.hosting_info': settings.hosting_info,
    'company.telegram_channel': settings.social_links?.telegram_channel || '',
    'company.telegram_bot': settings.social_links?.telegram_bot || '',
    'company.vk': settings.social_links?.vk || '',
    'company.max': settings.social_links?.max || '',
  };

  return text.replace(/\{\{\s*([a-zA-Z0-9_.]+)\s*\}\}/g, (match, key) => {
    return map[key] !== undefined ? map[key] : match;
  });
}

