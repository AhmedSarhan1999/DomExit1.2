const FAQ_STORAGE_KEY = 'domexit_faq_items_v1';

export class FAQRepository {
  private static getStored(): FaqItem[] {
    try {
      const raw = localStorage.getItem(FAQ_STORAGE_KEY);
      if (raw) {
        const parsed = JSON.parse(raw);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed;
        }
      }
    } catch (e) {
      console.warn('Failed to parse FAQ items from localStorage, using defaults', e);
    }
    try {
      localStorage.setItem(FAQ_STORAGE_KEY, JSON.stringify(INITIAL_FAQ_ITEMS));
    } catch {
      // ignore
    }
    return INITIAL_FAQ_ITEMS;
  }

  static async getAll(): Promise<FaqItem[]> {
    return this.getStored();
  }

  static async getByCategory(category: FaqCategory): Promise<FaqItem[]> {
    const list = this.getStored();
    return list.filter((item) => item.category === category);
  }

  static async search(query: string, category?: FaqCategory): Promise<FaqItem[]> {
    let list = this.getStored();
    if (category) {
      list = list.filter((i) => i.category === category);
    }
    const q = query.toLowerCase().trim();
    if (!q) return list;
    return list.filter(
      (item) =>
        item.question.toLowerCase().includes(q) ||
        item.answer.toLowerCase().includes(q) ||
        item.lawReferences?.some((law) => law.toLowerCase().includes(q))
    );
  }
}
