const STORAGE_KEY = 'domexit_knowledge_articles_v1';

export class KnowledgeRepository {
  private static getStored(): KnowledgeArticle[] {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (raw) {
        const parsed = JSON.parse(raw);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed;
        }
      }
    } catch (e) {
      console.warn('Failed to parse knowledge articles from localStorage, using defaults', e);
    }
    // Initialize storage with defaults
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_KNOWLEDGE_ARTICLES));
    } catch {
      // ignore
    }
    return INITIAL_KNOWLEDGE_ARTICLES;
  }

  static async getAll(): Promise<KnowledgeArticle[]> {
    return this.getStored();
  }

  static async getBySlug(slug: string): Promise<KnowledgeArticle | null> {
    const list = this.getStored();
    return list.find((a) => a.slug === slug) || null;
  }

  static async getByCategory(category: KnowledgeArticleCategory): Promise<KnowledgeArticle[]> {
    const list = this.getStored();
    return list.filter((a) => a.category === category);
  }

  static async search(query: string): Promise<KnowledgeArticle[]> {
    const list = this.getStored();
    const q = query.toLowerCase().trim();
    if (!q) return list;
    return list.filter(
      (a) =>
        a.title.toLowerCase().includes(q) ||
        a.excerpt.toLowerCase().includes(q) ||
        a.keywords.some((k) => k.toLowerCase().includes(q))
    );
  }
}
