import crypto from 'node:crypto';

export type PepDocumentType =
  | 'nda_viewing_act'
  | 'seller_exclusive_consent'
  | 'buyer_reservation_terms';

export interface GeneratedPepTemplate {
  documentType: PepDocumentType;
  documentTitle: string;
  documentVersion: string;
  canonicalText: string;
  documentTextHashSha256: string;
}

export function generatePepDocument(params: {
  documentType: PepDocumentType;
  lotCode: string;
  userEmail: string;
  userName?: string;
  userPhone?: string;
  dateStr?: string;
}): GeneratedPepTemplate {
  const { documentType, lotCode, userEmail, userName = 'Пользователь', dateStr } = params;
  const canonicalDate = dateStr || new Date().toISOString().split('T')[0];
  const version = '1.0';

  let documentTitle = '';
  let lines: string[] = [];

  if (documentType === 'nda_viewing_act') {
    documentTitle = 'Акт просмотра объекта и соглашение о конфиденциальности (ПЭП 63-ФЗ)';
    lines = [
      `СОГЛАШЕНИЕ О КОНФИДЕНЦИАЛЬНОСТИ И АКТ ПРОСМОТРА ОБЪЕКТА НЕДВИЖИМОСТИ`,
      `Идентификатор лота: #${lotCode}`,
      `Версия регламента: ${version}`,
      `Дата формирования: ${canonicalDate}`,
      ``,
      `1. СТОРОНЫ И ПРАВОВАЯ ОСНОВА:`,
      `Настоящий документ подписан простой электронной подписью (ПЭП) в соответствии с Федеральным законом № 63-ФЗ «Об электронной подписи» пользователем: ${userName} (${userEmail}).`,
      `Оператором защищенной платформы выступает сервис DomExit (ООО «ДомЭксит»).`,
      ``,
      `2. ОБЯЗАТЕЛЬСТВА О НЕРАЗГЛАШЕНИИ И ЗАЩИТЕ СДЕЛКИ:`,
      `2.1. Получатель информации (Покупатель/Инвестор) обязуется соблюдать строгую конфиденциальность в отношении сведений о лоте #${lotCode}, характеристиках ДДУ/ДКП, документах собственника и условиях уступки/продажи.`,
      `2.2. Запрет прямого обхода платформы (Anti-Circumvention): Пользователь обязуется не вступать в прямой контакт с продавцом объекта #${lotCode}, правообладателем или девелопером в обход платформы DomExit, а также не передавать полученные материалы третьим лицам или посредникам.`,
      `2.3. Все переговоры, юридический аудит, согласование скидок и проведение безопасных расчетов проводятся исключительно через аккредитованных кураторов DomExit и эскроу-сервисы уполномоченных банков.`,
      ``,
      `3. ЮРИДИЧЕСКАЯ СИЛА ПРОСТОЙ ЭЛЕКТРОННОЙ ПОДПИСИ (ПЭП):`,
      `Стороны признают, что ввод одноразового цифрового кода (SMS/Telegram OTP), направленного на верифицированный аккаунт пользователя, признается равнозначным собственноручной подписи на бумажном носителе в силу ст. 5 и ст. 9 Федерального закона № 63-ФЗ.`,
      `Хэш-сумма текста документа фиксируется в неизменяемом распределенном реестре платформы DomExit.`,
    ];
  } else if (documentType === 'seller_exclusive_consent') {
    documentTitle = 'Согласие продавца на аудит и размещение лота (ПЭП 63-ФЗ)';
    lines = [
      `СОГЛАСИЕ ПРОДАВЦА НА ПРОВЕДЕНИЕ ЮРИДИЧЕСКОГО АУДИТА И РАЗМЕЩЕНИЕ ЛОТА`,
      `Идентификатор лота: #${lotCode}`,
      `Версия регламента: ${version}`,
      `Дата формирования: ${canonicalDate}`,
      ``,
      `1. ПРЕДМЕТ СОГЛАСИЯ:`,
      `Собственник/Цедент: ${userName} (${userEmail}) поручает сервису DomExit провести независимый аудит юридической чистоты по лоту #${lotCode} (ФССП, ЕФРСБ 127-ФЗ, КАД Арбитраж, СФР Маткапитал, Росреестр) и упаковать объект в закрытый каталог платформы.`,
      ``,
      `2. УСЛОВИЯ СЕРВИСА:`,
      `2.1. Комиссия платформы DomExit с продавца составляет строго 0% (все расходы оплачивает покупатель).`,
      `2.2. Продавец гарантирует достоверность предоставленных сведений по договору ДДУ/ДКП, отсутствие скрытых обременений, запретов судебных приставов и претензий третьих лиц.`,
      `2.3. В силу Федерального закона № 152-ФЗ прямые контактные данные продавца не подлежат публикации в открытом доступе и передаются банку только на этапе регистрации сделки в Росреестре.`,
      ``,
      `3. ПОДТВЕРЖДЕНИЕ ПЭП:`,
      `Документ заверен простой электронной подписью согласно ст. 5 и 9 Федерального закона № 63-ФЗ.`,
    ];
  } else {
    documentTitle = 'Подтверждение условий бронирования и комиссии (ПЭП 63-ФЗ)';
    lines = [
      `ПОДТВЕРЖДЕНИЕ УСЛОВИЙ БРОНИРОВАНИЯ И ОПЛАТЫ КОМИССИИ 2.5%`,
      `Идентификатор лота: #${lotCode}`,
      `Версия регламента: ${version}`,
      `Дата формирования: ${canonicalDate}`,
      ``,
      `1. УСЛОВИЯ СДЕЛКИ:`,
      `Покупатель: ${userName} (${userEmail}) подтверждает фиксацию брони по лоту #${lotCode} и намерение приобрести объект через безопасные банковские расчеты (СБР Сбер / ВТБ / Банковский аккредитив).`,
      ``,
      `2. ОПЛАТА КОМИССИИ:`,
      `2.1. Вознаграждение сервиса DomExit составляет 2.5% от суммы сделки.`,
      `2.2. Оплата комиссии производится СТРОГО ПОСЛЕ успешной государственной регистрации перехода права/уступки в Управлении Росреестра и раскрытия банковского эскроу-счета/аккредитива. Никаких скрытых предоплат и авансов до регистрации не взимается.`,
      ``,
      `3. ПРАВОВОЙ СТАТУС ПЭП:`,
      `Настоящий документ сформирован в электронном виде и подписан кодом ПЭП (63-ФЗ). Хэш документа сохранен в неизменяемом журнале транзакций.`,
    ];
  }

  const canonicalText = lines.join('\n');
  const documentTextHashSha256 = crypto.createHash('sha256').update(canonicalText, 'utf-8').digest('hex');

  return {
    documentType,
    documentTitle,
    documentVersion: version,
    canonicalText,
    documentTextHashSha256,
  };
}
